"""
Deterministic (non-ML) language/script classification for the normalized corpus.

Method: `deterministic_unicode_script_plus_lexical_markers_v1`
No language-identification model or LLM call is used. Rationale (see
run_metadata/model_selection.md / FINAL_REPORT.md for the full writeup):
this corpus is template-generated by a small number of LLM sources, Hindi
closed-class function words (postpositions, pronouns, question words,
common verb endings) are a small, stable, high-recall vocabulary regardless
of topic, and genuinely ambiguous short prompts are explicitly routed to
`requires_manual_review` instead of being forced into a guess. A full
langid model (e.g. fastText lid.176, ~126MB) was judged unnecessary extra
weight for this closed, mostly-templated corpus; this is a judgment call,
not a proof, and is documented as a limitation.

Two independent signals are combined:
1. Unicode script ranges (exact, not a heuristic) -> `script`.
2. A closed-class Hindi lexical marker list, checked against whitespace
   tokens of Latin-script text -> distinguishes Hindi-in-Latin-script from
   English-in-Latin-script, and Hinglish (Hindi grammar + English content
   words) from pure Romanized Hindi.
"""
import re
import unicodedata

DEVANAGARI_RANGE = (0x0900, 0x097F)
LATIN_RANGES = [(0x0041, 0x005A), (0x0061, 0x007A), (0x00C0, 0x00FF), (0x0100, 0x024F)]

# Closed-class Hindi function words / question words / common verb endings,
# written in common Latin transliteration. Deliberately closed-class (not
# topic nouns) so the list stays small and high-precision across domains.
HINDI_LATIN_MARKERS = {
    # NOTE: "the", "to", and "men" are deliberately excluded even though they
    # are valid Hindi transliterations (the~the/were, to~toh, men~mein)
    # because they collide with extremely common English words and would
    # otherwise cause false Hindi-marker hits on plain English text.
    # NOTE: "hi" is also excluded -- collides with the English interjection
    # "hi" and, via tokenization splitting on the hyphen, with "Hi-C" (a real
    # molecular-biology method name that appears repeatedly in the DNA domain).
    "hai", "hain", "tha", "thi", "raha", "rahi", "rahe", "rha", "rhi",
    "ka", "ki", "ke", "ko", "se", "mein", "par", "ne", "aur", "ya",
    "lekin", "balki", "kyonki", "isliye", "jabki", "agar", "toh",
    "yeh", "ye", "woh", "voh", "yahan", "wahan", "jahan", "kahan",
    "kya", "kyun", "kaise", "kaun", "kis", "kisa", "kisko", "kiska", "kaunsa",
    "kitna", "kitne", "sab", "sabhi", "koi", "kuch", "nahi", "nahin",
    "chahiye", "chahie", "liye", "waala", "wala", "waali", "wali", "waale", "wale",
    "samjhaiye", "samjhao", "batayein", "bataiye", "dijiye", "deejiye",
    "kijiye", "kariye", "karo", "karte", "karta", "karti", "karna", "karne",
    "hoga", "hogi", "honge", "hua", "hui", "hue", "gaya", "gayi", "gaye",
    "arth", "sandarbh", "sandarbhik", "prakar", "prakara", "roop", "niyam",
    "tulnatmak", "samay", "sahi", "thoda", "alag", "bhi", "ab", "phir",
    "apna", "apni", "apne", "uska", "uski", "uske", "iska", "iski", "iske",
}

# Small closed-class English function-word set: used only as a secondary
# confidence booster for clearly-English text, not as the primary signal.
ENGLISH_LATIN_MARKERS = {
    "the", "is", "are", "was", "were", "a", "an", "of", "in", "on", "to",
    "and", "or", "what", "how", "why", "which", "does", "do", "that", "this",
    "be", "with", "for", "as", "by", "not", "its", "it", "can", "could",
    "would", "should", "will", "explain", "describe", "identify", "using",
}

# Common English *content* loanwords observed in this corpus's code-switched
# (Hinglish) workplace/office-register prompts. Used only to corroborate a
# hinglish call -- absence of a marker word is NOT itself evidence of English
# content (Hindi has a large open-class vocabulary not covered by the closed
# HINDI_LATIN_MARKERS list above; see FINAL_REPORT.md limitations).
ENGLISH_CONTENT_LOANWORDS = {
    "job", "interview", "salary", "negotiation", "candidate", "expectations",
    "policy", "impact", "feedback", "presentation", "response", "meeting",
    "email", "report", "deadline", "teacher", "class", "manager", "customer",
    "project", "phone", "resume", "appraisal", "target", "budget", "client",
    "service", "quality", "performance", "training", "schedule", "discount",
    "refund", "warranty", "invoice", "order", "delivery", "complaint",
    "suggestion", "review", "sense", "level", "ground", "transparent",
    "politely", "professionally", "tech", "mall", "party", "sentence",
    "scope", "clause", "logic", "relative", "antecedent", "negotiation",
}

TOKEN_RE = re.compile(r"[A-Za-z]+|[ऀ-ॿ]+")


def _char_script_counts(text: str):
    devanagari = latin = other_letter = non_letter = 0
    for ch in text:
        code = ord(ch)
        if DEVANAGARI_RANGE[0] <= code <= DEVANAGARI_RANGE[1]:
            devanagari += 1
        elif any(lo <= code <= hi for lo, hi in LATIN_RANGES):
            latin += 1
        elif unicodedata.category(ch).startswith("L"):
            other_letter += 1
        else:
            non_letter += 1
    return devanagari, latin, other_letter, non_letter


def classify(text: str) -> dict:
    devanagari, latin, other_letter, non_letter = _char_script_counts(text)
    letter_total = devanagari + latin + other_letter

    tokens = TOKEN_RE.findall(text)
    latin_tokens = [t for t in tokens if t.isascii() and t.isalpha()]
    devanagari_tokens = [t for t in tokens if any(
        DEVANAGARI_RANGE[0] <= ord(c) <= DEVANAGARI_RANGE[1] for c in t
    )]
    token_total = len(tokens)

    hindi_marker_hits = sum(1 for t in latin_tokens if t.lower() in HINDI_LATIN_MARKERS)
    english_marker_hits = sum(1 for t in latin_tokens if t.lower() in ENGLISH_LATIN_MARKERS)
    content_loanword_hits = sum(1 for t in latin_tokens if t.lower() in ENGLISH_CONTENT_LOANWORDS)
    hindi_marker_ratio = hindi_marker_hits / token_total if token_total else 0.0
    english_marker_ratio = english_marker_hits / token_total if token_total else 0.0

    debug = {
        "devanagari_char_count": devanagari, "latin_char_count": latin,
        "other_letter_char_count": other_letter, "token_count": token_total,
        "latin_token_count": len(latin_tokens), "devanagari_token_count": len(devanagari_tokens),
        "hindi_marker_hits": hindi_marker_hits, "english_marker_hits": english_marker_hits,
        "content_loanword_hits": content_loanword_hits,
        "hindi_marker_ratio": round(hindi_marker_ratio, 4),
        "english_marker_ratio": round(english_marker_ratio, 4),
    }

    if letter_total == 0:
        return _result("none", "uncertain", "uncertain", 0.1, True, debug)

    devanagari_ratio = devanagari / letter_total
    latin_ratio = latin / letter_total
    other_ratio = other_letter / letter_total

    # --- script ---
    if other_ratio >= 0.5:
        script = "other"
    elif devanagari_ratio >= 0.85:
        script = "Devanagari"
    elif latin_ratio >= 0.85:
        script = "Latin"
    elif devanagari_ratio > 0.0 and latin_ratio > 0.0:
        script = "mixed"
    elif devanagari_ratio > 0.0:
        script = "Devanagari"
    elif latin_ratio > 0.0:
        script = "Latin"
    else:
        script = "uncertain"

    # --- language / language_form ---
    if script == "other":
        return _result(script, "other", "other", 0.5, True, debug)

    if script == "Devanagari":
        # pure or near-pure Devanagari
        if latin_ratio > 0.0 and len(latin_tokens) / token_total >= 0.2:
            return _result("mixed", "mixed", "mixed_multilingual", 0.8, False, debug)
        return _result(script, "Hindi", "native_hindi", 0.97, False, debug)

    if script == "mixed":
        # Devanagari-dominant with a notable embedded Latin/English fraction
        latin_token_frac = len(latin_tokens) / token_total if token_total else 0.0
        if latin_token_frac >= 0.2:
            return _result(script, "mixed", "mixed_multilingual", 0.78, False, debug)
        return _result(script, "Hindi", "native_hindi", 0.85, False, debug)

    # script == "Latin": distinguish English / Romanized Hindi / Hinglish / uncertain
    if token_total < 4:
        # too short for the lexical heuristic to be reliable
        if hindi_marker_ratio > 0:
            return _result(script, "Hindi", "romanized_hindi", 0.55, True, debug)
        return _result(script, "uncertain", "uncertain", 0.4, True, debug)

    non_marker_ratio = 1 - hindi_marker_ratio - english_marker_ratio

    if hindi_marker_ratio >= 0.12:
        # Strong closed-class Hindi grammar signal present. Absence of a marker
        # word is NOT itself evidence of English content (Hindi's open-class
        # vocabulary is far bigger than HINDI_LATIN_MARKERS) -- only promote to
        # "hinglish" when real English content loanwords corroborate it.
        loanword_ratio = content_loanword_hits / token_total if token_total else 0.0
        if non_marker_ratio >= 0.70 and (english_marker_ratio >= 0.03 or content_loanword_hits >= 2):
            return _result(script, "mixed", "hinglish", 0.75, False, debug)
        if non_marker_ratio >= 0.45 and (english_marker_ratio > 0 or content_loanword_hits >= 1):
            # corroborated but weaker signal -- plausible Hinglish, flag for review
            return _result(script, "mixed", "hinglish", 0.55, True, debug)
        # high non-marker ratio with NO English corroboration: most likely just
        # Hindi vocabulary not covered by the closed-class marker list, not English
        return _result(script, "Hindi", "romanized_hindi", 0.70, False, debug)

    if hindi_marker_ratio == 0:
        # No Hindi signal at all in a Latin-script prompt. In this corpus the only
        # two realistic language families are English and Hindi/Hinglish, so the
        # absence of any Hindi marker is itself reasonable (if not airtight)
        # evidence of English -- including terse prompts with no closed-class
        # English stopwords either (e.g. "Distinguish embarrassment from awkwardness.").
        if token_total <= 2:
            return _result(script, "uncertain", "uncertain", 0.4, True, debug)
        if english_marker_ratio >= 0.08 or token_total >= 6:
            return _result(script, "English", "english", 0.88, False, debug)
        return _result(script, "English", "english", 0.65, False, debug)

    # weak/no signal either way
    return _result(script, "uncertain", "uncertain", 0.45, True, debug)


def _result(script, language, language_form, confidence, requires_review, debug):
    return {
        "script": script,
        "language": language,
        "language_form": language_form,
        "classification_method": "deterministic_unicode_script_plus_lexical_markers_v1",
        "classification_confidence": round(confidence, 3),
        "requires_manual_review": requires_review,
        "debug": debug,
    }
